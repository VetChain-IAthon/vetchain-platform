from typing import Protocol

from app.modules.settings.domain.entities import CustomerLevelRule, LevelRules, LevelThresholds, PricingSettings


class SettingsRepository(Protocol):
    def get_pricing(self) -> PricingSettings: ...

    def save_pricing(self, pricing: PricingSettings) -> None: ...

    def get_level_rules(self) -> LevelRules: ...

    def save_level_rule(self, rule: CustomerLevelRule) -> None: ...

    def get_thresholds(self) -> LevelThresholds: ...

    def save_thresholds(self, thresholds: LevelThresholds) -> None: ...
